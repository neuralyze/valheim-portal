#!/usr/bin/env python3
"""Derive the per-world, per-preset jumpstart tree.

    tools/jumpstart/presets/<preset>.yaml   WORLD-AGNOSTIC tier definition
    tools/jumpstart/worlds/tier-policy.yaml WORLD-AGNOSTIC tier -> settings policy
    tools/jumpstart/worlds/<World>/world.yaml   WORLD-SPECIFIC facts
        |
        +--> tools/jumpstart/worlds/<World>/<preset>/
                 settings/world-modifiers.env    generated
                 settings/overrides.yaml         generated
                 settings/chest-manifest.yaml    generated
                 keys.yaml                       generated
                 charactertemplate.yml           generated
                 spawn.yaml                      generated by `spawn` (needs terrain)
                 blueprints/                     created empty, owned by others
                 placements.yaml                 NOT written; read if present

Nothing here is hand-maintained. Every generated file carries a provenance
header naming the three inputs, and `--check` re-derives in memory and diffs, so
a hand edit or a stale regenerate is detectable rather than silent.

    derive.py list
    derive.py build <World> [--preset NAME ...]
    derive.py check <World> [--preset NAME ...]
    derive.py spawn <World> [--preset NAME ...] [--check]

`build` writes; `check` never writes and exits 1 on drift.

The template's `spawn:` block is the one coordinate this tree emits, and it is
the one thing it cannot derive from YAML alone: a coordinate is only usable if
the ground under it is dry. `spawn` probes Valheim's own generator at 1 m
through tools/jumpstart/blueprints/run_patchscan.sh, picks a point that is
verifiably on land next to the placement, and records the evidence in
spawn.yaml. `build` and `check` then need no terrain at all: they cross-check
spawn.yaml against the CURRENT `solved` blocks, which is the check whose absence
put a character in the sea -- the solver re-solved, the base moved, and nothing
compared the two.

A template is also REFUSED when the kit it would put on the character weighs
more than the world's carry budget. Slots were the only capacity this tool used
to model, and a kit can fit in 32 slots and still spawn the player OVERBURDENED:
MEASURED on 2026-09-15, pre-bonemass rendered 30 prefabs into 32 slots weighing
426.8 kg against Valheim's 300 kg limit, and the operator found that by being
unable to walk rather than by running this tool. Weights come from
tools/jumpstart/data/item_weights.json (read out of the game's own asset
bundles); the capacity and the budget come from world.yaml `inventory:`.
"""
