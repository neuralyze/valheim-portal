def footprint_half_extents(pl: dict) -> tuple[float, float]:
    """Half extents of the blueprint's own footprint, in its own axes.

    placements.yaml records footprint_xzy_m as the measured x/z/y extent of the
    unrotated blueprint; the yaw is applied separately, when a point is taken
    into the building's frame. The requirement's search square is the fallback
    only when the real footprint is missing.
    """
    fp = pl.get("footprint_xzy_m") or []
    if len(fp) >= 2:
        return float(fp[0]) / 2.0, float(fp[1]) / 2.0
    side = float((pl.get("requirement") or {}).get("footprint_m", 56.0))
    return side / 2.0, side / 2.0


def placement_yaw(pl: dict) -> float:
    return float((pl.get("rotation") or {}).get("yaw", 0.0) or 0.0)


def _to_local(px, pz, cx: float, cz: float, yaw_deg: float):
    """World delta from a placement's centre, rotated into the building's axes.

    Same convention as placements.yaml's own rotation_convention: Unity euler Y,
    +yaw turning the building clockwise seen from above, so the world delta is
    rotated by -yaw. Scalars in the audit, numpy planes in the probe -- one
    implementation, so the two can never disagree about which way is forward.
    """
    a = math.radians(yaw_deg)
    ca, sa = math.cos(a), math.sin(a)
    dx, dz = px - cx, pz - cz
    return dx * ca - dz * sa, dx * sa + dz * ca


def rect_distance(px, pz, cx: float, cz: float, hx: float, hz: float, yaw_deg: float):
    """Distance from a point to a yawed rectangle; 0 inside it."""
    lx, lz = _to_local(px, pz, cx, cz, yaw_deg)
    ox = abs(lx) - hx
    oz = abs(lz) - hz
    if hasattr(ox, "clip"):
        ox = ox.clip(min=0.0)
        oz = oz.clip(min=0.0)
        return (ox * ox + oz * oz) ** 0.5
    return math.hypot(max(ox, 0.0), max(oz, 0.0))


def rect_nearest(px: float, pz: float, cx: float, cz: float, hx: float, hz: float, yaw_deg: float):
    """The point on the rectangle's edge a walker would head for."""
    lx, lz = _to_local(px, pz, cx, cz, yaw_deg)
    nx = min(max(lx, -hx), hx)
    nz = min(max(lz, -hz), hz)
    a = math.radians(yaw_deg)
    ca, sa = math.cos(a), math.sin(a)
    return cx + (nx * ca + nz * sa), cz + (-nx * sa + nz * ca)


def patch_origin(patch: dict) -> tuple[int, int]:
    """World coordinate of patch sample (0, 0), which MUST be an integer.

    PatchScan samples (i, j) at cx - half + j*step + step/2. With step 1, an
    integer half and a half-integer centre that lands exactly on integer world
    coordinates -- which is the whole point. `spawn` takes integers, so the
    verdict has to be taken at the integer that gets written, not half a cell
    away from it; the candidates here ARE lattice points, so there is no rounding
    after the fact to invalidate them.
    """
    x0 = patch["cx"] - patch["half"] + patch["step"] * 0.5
    z0 = patch["cz"] - patch["half"] + patch["step"] * 0.5
    if abs(x0 - round(x0)) > 1e-6 or abs(z0 - round(z0)) > 1e-6:
        raise SystemExit(
            f"patch at ({patch['cx']}, {patch['cz']}) half={patch['half']} "
            f"step={patch['step']} does not sample integer coordinates"
        )
    return int(round(x0)), int(round(z0))


def patch_rows(world: World, presets: list) -> list[tuple[str, float, float, float, float]]:
    """One 1 m patch request per solved placement, centred on the placement."""
    rows: list[tuple[str, float, float, float, float]] = []
    for preset in presets:
        placements = load_placements(world.root / preset.name)
        for pid, pl in sorted(solved_placements(placements).items()):
            hx, hz = footprint_half_extents(pl)
            half = float(
                math.ceil(math.hypot(hx, hz) + SPAWN_SEARCH_MAX_M + SPAWN_PROBE_PAD_M)
            )
            sol = pl["solved"]
            rows.append(
                (
                    f"{preset.name}#{pid}",
                    round(float(sol["x"])) + 0.5,
                    round(float(sol["z"])) + 0.5,
                    half,
                    SPAWN_PROBE_STEP_M,
                )
            )
    return rows


def patch_covers(rows, patches: dict) -> bool:
    """Does this patch file actually answer the request we are about to make?"""
    for pid, cx, cz, half, step in rows:
        p = patches.get(pid)
        if p is None:
            return False
        if abs(p["cx"] - cx) > 1e-3 or abs(p["cz"] - cz) > 1e-3:
            return False
        if abs(p["step"] - step) > 1e-6 or p["half"] + 1e-3 < half:
            return False
    return True


def run_patchscan(seed: str, rows, patch: Path, vh_src: str, sandbox: str | None) -> None:
    req = patch.with_suffix(".req.tsv")
    patch.parent.mkdir(parents=True, exist_ok=True)
    req.write_text(
        "".join(f"{i}\t{cx}\t{cz}\t{half}\t{step}\n" for i, cx, cz, half, step in rows),
        "utf-8",
    )
    env = dict(os.environ, VH_SRC=vh_src, SEED=seed, REQ=str(req), OUT=str(patch))
    if sandbox:
        env["SANDBOX"] = sandbox
    # Boots the dedicated server in an rsync'd sandbox on its own port and
    # savedir, exactly as the placement solver's 1 m pass does. Nothing live.
    subprocess.run([str(PATCHSCAN)], env=env, check=True)


def dry_approach(patch: dict, origin: tuple[int, int], sx: int, sz: int, tx: float, tz: float) -> dict:
    """Walk 1 m at a time from the spawn to the footprint edge and report.

    Intermediate steps are not lattice points, so each is read at its nearest
    integer sample: at most 0.71 m of horizontal error on a walk whose purpose is
    to find water and cliffs, both of which are metres wide. The endpoints are
    exact -- the spawn IS a lattice point.

    Any water at all fails the walk, INCLUDING water at the base end. A base
    site that is itself below the water plane cannot have a spawn that is both
    next to it and joined to it by dry ground, and the right answer there is to
    refuse and re-solve the site, not to ship the least-bad point: a missing
    spawn is a visible gap, a wet one is a bug that reaches the operator.
    """
    height = patch["height"]
    n = patch["n"]
    x0, z0 = origin
    span = math.hypot(tx - sx, tz - sz)
    steps = max(1, int(math.ceil(span)))
    free: list[float] = []
    for k in range(steps + 1):
        t = k / steps
        j = int(round(sx + (tx - sx) * t)) - x0
        i = int(round(sz + (tz - sz) * t)) - z0
        if not (0 <= i < n and 0 <= j < n):
            return {"ok": False, "reason": "approach leaves the probed window"}
        free.append(float(height[i, j]) - SEA_LEVEL_M)
    worst_wet = min(free)
    if worst_wet < SPAWN_PATH_FREEBOARD_M:
        return {
            "ok": False,
            "reason": f"approach crosses water ({worst_wet:.2f} m relative to the water plane)",
        }
    steps_m = [abs(free[k + 1] - free[k]) for k in range(len(free) - 1)]
    worst = max(steps_m) if steps_m else 0.0
    if worst > SPAWN_PATH_STEP_M:
        return {"ok": False, "reason": f"approach steps {worst:.2f} m in one metre"}
    return {
        "ok": True,
        "length_m": round(span, 1),
        "min_freeboard_m": round(worst_wet, 2),
        "max_step_m": round(worst, 2),
        "dry_to_footprint_edge": True,
    }


def probe_spawn(patch: dict, pl: dict) -> dict:
    """Pick this placement's spawn out of its 1 m patch, or refuse and say why.

    Every candidate is an integer world coordinate that is: at least
    SPAWN_FOOTPRINT_CLEAR_M outside the blueprint's rotated footprint and at most
    SPAWN_SEARCH_MAX_M outside it; SPAWN_FREEBOARD_M above the water plane at the
    exact written point; above SPAWN_DISC_FREEBOARD_M across a SPAWN_DISC_R_M
    disc; and joined to the footprint edge by a metre-by-metre walk that stays
    out of the water and off cliffs. Nothing is inferred -- if no such point
    exists the return value is a refusal carrying the numbers that explain it.
    """
    import numpy as np
    from scipy import ndimage

    sol = pl["solved"]
    bx, bz = float(sol["x"]), float(sol["z"])
    hx, hz = footprint_half_extents(pl)
    yaw = placement_yaw(pl)
    origin = patch_origin(patch)
    x0, z0 = origin
    n = patch["n"]
    free = patch["height"].astype(np.float64) - SEA_LEVEL_M
    X, Z = np.meshgrid(
        x0 + np.arange(n, dtype=np.float64), z0 + np.arange(n, dtype=np.float64)
    )
    edge = rect_distance(X, Z, bx, bz, hx, hz, yaw)
    r = int(SPAWN_DISC_R_M)
    dy, dx = np.mgrid[-r : r + 1, -r : r + 1]
    # A poisoned border means a candidate whose disc leaves the probed window
    # loses, rather than winning on evidence that was never gathered.
    disc = ndimage.minimum_filter(
        free, footprint=(dx * dx + dy * dy) <= r * r, mode="constant", cval=-1e9
    )
    ring = (edge >= SPAWN_FOOTPRINT_CLEAR_M) & (edge <= SPAWN_SEARCH_MAX_M)
    dry = free >= SPAWN_FREEBOARD_M
    ok = ring & dry & (disc >= SPAWN_DISC_FREEBOARD_M)
    base_free = float(free[round(bz) - z0, round(bx) - x0])
    nearest_dry = None
    if dry.any():
        nearest_dry = round(
            float(np.hypot(X[dry] - bx, Z[dry] - bz).min()), 1
        )
    counts = {
        "in_ring": int(ring.sum()),
        "ring_and_freeboard": int((ring & dry).sum()),
        "ring_freeboard_and_disc": int(ok.sum()),
        "nearest_freeboard_m": nearest_dry,
        "base_freeboard_m": round(base_free, 2),
    }
    if not ok.any():
        return {"refused": _refusal(counts), "counts": counts}

    iz, ix = np.nonzero(ok)
    cand_x = (x0 + ix).astype(np.int64)
    cand_z = (z0 + iz).astype(np.int64)
    cand_edge = edge[iz, ix]
    cand_free = free[iz, ix]
    cand_disc = disc[iz, ix]
    # Bearing agreement with the side the building faces. placements.yaml's yaw
    # convention makes the facade normal (sin yaw, cos yaw) in world axes, which
    # is the same vector the placement solver offsets its own naive point along.
    a = math.radians(yaw)
    fx, fz = math.sin(a), math.cos(a)
    dxv = cand_x - bx
    dzv = cand_z - bz
    norm = np.hypot(dxv, dzv)
    norm[norm == 0] = 1.0
    facade = ((dxv * fx + dzv * fz) / norm + 1.0) / 2.0
    near = 1.0 - np.clip(
        (cand_edge - SPAWN_FOOTPRINT_CLEAR_M)
        / max(SPAWN_SEARCH_MAX_M - SPAWN_FOOTPRINT_CLEAR_M, 1e-9),
        0.0,
        1.0,
    )
    dryness = np.clip(cand_free / (2.0 * SPAWN_FREEBOARD_M), 0.0, 1.0)
    score = (
        SPAWN_WEIGHTS["near"] * near
        + SPAWN_WEIGHTS["facade"] * facade
        + SPAWN_WEIGHTS["dry"] * dryness
    )
    order = np.argsort(-score)
    rejected: dict[str, int] = {}
    tried = 0
    seen_cells: set[tuple[int, int]] = set()
    sep = max(1.0, SPAWN_TRY_SEPARATION_M)
    for k in order:
        if tried >= SPAWN_APPROACH_TRIES:
            break
        sx, sz = int(cand_x[k]), int(cand_z[k])
        cell = (int(math.floor(sx / sep)), int(math.floor(sz / sep)))
        if cell in seen_cells:
            continue
        seen_cells.add(cell)
        tried += 1
        tx, tz = rect_nearest(float(sx), float(sz), bx, bz, hx, hz, yaw)
        walk = dry_approach(patch, origin, sx, sz, tx, tz)
        if not walk["ok"]:
            rejected[walk["reason"]] = rejected.get(walk["reason"], 0) + 1
            continue
        terrain = round(float(cand_free[k]) + SEA_LEVEL_M, 2)
        return {
            "point": {
                "x": sx,
                # ceil of the RECORDED terrain, not of the raw float, so `check`
                # re-deriving y from this file gets the same integer.
                "y": int(math.ceil(terrain + SPAWN_Y_CLEAR_M)),
                "z": sz,
                "base": str(pl.get("id")),
                "base_xz": [bx, bz],
                "base_y": float(sol.get("y")) if sol.get("y") is not None else None,
                "base_freeboard_m": round(base_free, 2),
                "terrain_y": terrain,
                "spawn_freeboard_m": round(terrain - SEA_LEVEL_M, 2),
                "disc_min_freeboard_m": round(float(cand_disc[k]), 2),
                "dist_to_base_m": round(math.hypot(sx - bx, sz - bz), 1),
                "dist_to_footprint_edge_m": round(float(cand_edge[k]), 1),
                "footprint_half_extents_m": [hx, hz],
                "yaw": yaw,
                "facade_agreement": round(float(facade[k]), 3),
                "score": round(float(score[k]), 3),
                "approach": {kk: vv for kk, vv in walk.items() if kk != "ok"},
                "candidates_considered": int(ok.sum()),
            }
        }
    counts["approach_rejections"] = rejected
    counts["approach_tried"] = tried
    return {
        "base": str(pl.get("id")),
        "base_xz": [bx, bz],
        "refused": _refusal(counts),
        "counts": counts,
    }


def _refusal(counts: dict) -> str:
    """One sentence an operator can act on, built from the numbers we measured."""
    base_free = counts["base_freeboard_m"]
    submerged = (
        f" The placement itself is {abs(base_free):.2f} m BELOW the water plane, so no point "
        "next to it can be reached without swimming: re-solve the SITE."
        if base_free < 0
        else ""
    )
    if not counts["in_ring"]:
        return (
            f"no integer coordinate lies {SPAWN_FOOTPRINT_CLEAR_M:.0f}-"
            f"{SPAWN_SEARCH_MAX_M:.0f} m outside the footprint inside the probed window."
            + submerged
        )
    near = counts["nearest_freeboard_m"]
    if not counts["ring_and_freeboard"]:
        where = (
            f"{near:.0f} m from the placement centre"
            if near is not None
            else "nowhere in the probed window"
        )
        return (
            f"no ground with {SPAWN_FREEBOARD_M:.0f} m of freeboard within "
            f"{SPAWN_SEARCH_MAX_M:.0f} m of the footprint; the nearest such ground is "
            f"{where}." + submerged
        )
    if not counts["ring_freeboard_and_disc"]:
        return (
            f"{counts['ring_and_freeboard']} dry point(s) in range, none holding "
            f"{SPAWN_DISC_FREEBOARD_M:.1f} m of freeboard across a {SPAWN_DISC_R_M:.0f} m disc "
            "-- every one of them is a pinnacle or a shoreline." + submerged
        )
    reasons = ", ".join(
        f"{v}x {k}" for k, v in sorted(counts.get("approach_rejections", {}).items())
    )
    return (
        f"{counts['ring_freeboard_and_disc']} dry point(s) in range, and none of the "
        f"{counts.get('approach_tried', 0)} best is walkable to the footprint edge "
        f"({reasons or 'no candidate reached the approach test'})." + submerged
    )


