def load_spawn_file(preset_dir: Path) -> dict | None:
    path = preset_dir / SPAWN_FILE
    if not path.exists():
        return None
    raw = yaml.safe_load(path.read_text("utf-8")) or {}
    if not isinstance(raw, dict):
        raise SystemExit(f"{path}: expected a YAML mapping")
    return raw


def audit_spawn(
    world: World, preset, placements: dict | None, spawn_doc: dict | None
) -> tuple[list[dict], list[str]]:
    """Cross-check spawn.yaml against the CURRENT placements.yaml.

    This is the check that did not exist, and its absence is how a character was
    dropped in the sea: the `solved` blocks are re-solved by one tool, the
    template is rendered by another, and nothing ever compared the two. Pure
    geometry plus the evidence the probe recorded, so it needs no Valheim server
    and no 34 MB grid -- it runs wherever `check` runs.
    """
    problems: list[str] = []
    solved = solved_placements(placements)
    regen = f"tools/jumpstart/worlds/derive.py spawn {world.name} --preset {preset.name}"
    tag = f"{world.name}/{preset.name}"
    if not solved:
        if spawn_doc and (spawn_doc.get("points") or spawn_doc.get("refused")):
            problems.append(
                f"{tag}: {SPAWN_FILE} records spawn work but placements.yaml has no solved "
                f"placement left. Delete it or re-solve. Run: {regen}"
            )
        return [], problems
    if spawn_doc is None:
        problems.append(
            f"{tag}: placements.yaml has {len(solved)} solved placement(s) and no {SPAWN_FILE}, "
            f"so no spawn has ever been verified against terrain. Run: {regen}"
        )
        return [], problems
    seed = str(world.raw.get("seed"))
    if str(spawn_doc.get("seed")) != seed:
        problems.append(
            f"{tag}: {SPAWN_FILE} was probed on seed {spawn_doc.get('seed')!r} but world.yaml "
            f"says {seed!r}. Every coordinate in it belongs to a different world. Run: {regen}"
        )
    if float(spawn_doc.get("sea_level_m", -1)) != SEA_LEVEL_M:
        problems.append(
            f"{tag}: {SPAWN_FILE} was verified against sea level "
            f"{spawn_doc.get('sea_level_m')}, this tool now uses {SEA_LEVEL_M}. Run: {regen}"
        )
    points = [p for p in (spawn_doc.get("points") or []) if isinstance(p, dict)]
    refused = [r for r in (spawn_doc.get("refused") or []) if isinstance(r, dict)]
    covered: set[str] = set()

    def base_moved(entry: dict, what: str) -> bool:
        base = str(entry.get("base"))
        pl = solved.get(base)
        if pl is None:
            problems.append(
                f"{tag}: {what} was derived from placement {base!r}, which no longer has a "
                f"solved site. Run: {regen}"
            )
            return True
        sol = pl["solved"]
        rec = entry.get("base_xz") or [None, None]
        now_x, now_z = float(sol["x"]), float(sol["z"])
        if rec[0] is None or abs(float(rec[0]) - now_x) > 0.01 or abs(float(rec[1]) - now_z) > 0.01:
            moved = (
                math.hypot(float(rec[0]) - now_x, float(rec[1]) - now_z)
                if rec[0] is not None
                else float("nan")
            )
            problems.append(
                f"{tag}: {what} was verified against {base} at "
                f"({rec[0]}, {rec[1]}) but that placement is now at ({now_x}, {now_z}), "
                f"{moved:.0f} m away. The terrain verdict no longer applies to the spawn that "
                f"would ship. Run: {regen}"
            )
            return True
        return False

    for pt in points:
        base = str(pt.get("base"))
        covered.add(base)
        x, y, z = pt.get("x"), pt.get("y"), pt.get("z")
        what = f"spawn ({x}, {y}, {z})"
        if not all(isinstance(v, int) for v in (x, y, z)):
            problems.append(
                f"{tag}: {what} is not three integers, which is the only thing "
                f"ServerCharacters' `spawn:` accepts. Run: {regen}"
            )
            continue
        if base_moved(pt, what):
            continue
        pl = solved[base]
        terrain = pt.get("terrain_y")
        if not isinstance(terrain, (int, float)):
            problems.append(f"{tag}: {what} records no terrain_y, so it is unverified. Run: {regen}")
            continue
        margin = round(float(terrain) - SEA_LEVEL_M, 2)
        if margin + 1e-9 < SPAWN_FREEBOARD_M:
            problems.append(
                f"{tag}: {what} stands on terrain {terrain}, which is {margin} m above the "
                f"water plane ({SEA_LEVEL_M}); the floor is {SPAWN_FREEBOARD_M} m. That is a "
                f"spawn in the water. Run: {regen}"
            )
        want_y = int(math.ceil(float(terrain) + SPAWN_Y_CLEAR_M))
        if y != want_y:
            problems.append(
                f"{tag}: {what} should have y={want_y} for terrain {terrain} "
                f"(ceil(terrain + {SPAWN_Y_CLEAR_M})). Run: {regen}"
            )
        disc = pt.get("disc_min_freeboard_m")
        if not isinstance(disc, (int, float)) or float(disc) + 1e-9 < SPAWN_DISC_FREEBOARD_M:
            problems.append(
                f"{tag}: {what} records {disc} m of freeboard across its "
                f"{SPAWN_DISC_R_M} m disc; the floor is {SPAWN_DISC_FREEBOARD_M} m. Run: {regen}"
            )
        hx, hz = footprint_half_extents(pl)
        sol = pl["solved"]
        edge = rect_distance(
            float(x), float(z), float(sol["x"]), float(sol["z"]), hx, hz, placement_yaw(pl)
        )
        if edge + 1e-6 < SPAWN_FOOTPRINT_CLEAR_M:
            problems.append(
                f"{tag}: {what} is {edge:.1f} m from the {2 * hx:g}x{2 * hz:g} m footprint of "
                f"{base}; the stand-off is {SPAWN_FOOTPRINT_CLEAR_M} m, so a player would wake "
                f"up inside the building. Run: {regen}"
            )
        if edge - 1e-6 > SPAWN_SEARCH_MAX_M:
            problems.append(
                f"{tag}: {what} is {edge:.1f} m outside {base}'s footprint, past the "
                f"{SPAWN_SEARCH_MAX_M} m limit. Run: {regen}"
            )
        walk = pt.get("approach") or {}
        if walk.get("max_step_m") is None or float(walk["max_step_m"]) > SPAWN_PATH_STEP_M:
            problems.append(
                f"{tag}: {what} records an approach that steps {walk.get('max_step_m')} m in "
                f"one metre; the limit is {SPAWN_PATH_STEP_M} m. Run: {regen}"
            )
        if (
            walk.get("min_freeboard_m") is None
            or float(walk["min_freeboard_m"]) + 1e-9 < SPAWN_PATH_FREEBOARD_M
        ):
            problems.append(
                f"{tag}: {what} records an approach whose lowest ground is "
                f"{walk.get('min_freeboard_m')} m over the water plane; the floor is "
                f"{SPAWN_PATH_FREEBOARD_M} m, so the walk to the base goes through water. "
                f"Run: {regen}"
            )

    for entry in refused:
        covered.add(str(entry.get("base")))
        base_moved(entry, f"the recorded refusal for {entry.get('base')!r}")

    for base in sorted(set(solved) - covered):
        problems.append(
            f"{tag}: placement {base} has a solved site with neither a verified spawn nor a "
            f"recorded refusal in {SPAWN_FILE}. Run: {regen}"
        )
    return [p for p in points if all(isinstance(p.get(k), int) for k in "xyz")], problems


