def generate(
    world: World, preset, policy: dict, measured, fallbacks, table: ItemTable, spawn: list[dict]
) -> tuple[dict[str, str], list[str]]:
    """(files, kit problems). Problems are returned, never printed here."""
    preset_dir = world.root / preset.name
    part = partition(preset, world, measured, fallbacks, table)
    capacity = load_container_capacity(load_placements(preset_dir))
    files = {
        "settings/world-modifiers.env": render_modifiers(world, preset, policy),
        "settings/overrides.yaml": render_overrides(world, preset, policy),
        "settings/chest-manifest.yaml": render_chest_manifest(world, preset, part, capacity),
        "keys.yaml": render_keys(world, preset, policy),
        "charactertemplate.yml": render_template(world, preset, part, spawn, table),
    }
    return files, kit_problems(world, preset, part, table)


def run(world_name: str, preset_names: list[str] | None, write: bool) -> int:
    world = load_world(world_name)
    policy = load_policy()
    measured, fallbacks = load_stacks(world)
    table = load_item_table(world)
    if not measured:
        print(
            f"warning: stack table {world.stack_table_path} not readable; "
            "slot costs fall back to one slot per item",
            file=sys.stderr,
        )
    names = preset_names or js.all_preset_names()

    drift = 0
    for name in names:
        preset = js.load_preset(name)
        preset_dir = world.root / name
        placements = load_placements(preset_dir)
        spawn, problems = audit_spawn(world, preset, placements, load_spawn_file(preset_dir))
        files, overweight = generate(
            world, preset, policy, measured, fallbacks, table, spawn
        )
        if problems:
            # The template is the only file that carries a coordinate, so it is
            # the only one held back: shipping a spawn whose terrain verdict no
            # longer applies is the failure this check exists to stop.
            files.pop("charactertemplate.yml", None)
            for problem in problems:
                print(f"SPAWN    {problem}", file=sys.stderr)
            drift += len(problems)
            print(f"{'HELD':8s} {world.name}/{name}/charactertemplate.yml")
        if overweight:
            # Same rule, different limit. A template that would spawn the player
            # overburdened -- or wearing nothing, or wearing one of two items it
            # names -- is worse than a missing one: the missing one is a visible
            # gap, the wrong one reaches the player and is only found in game.
            held = "charactertemplate.yml" in files
            files.pop("charactertemplate.yml", None)
            for problem in overweight:
                print(f"KIT      {problem}", file=sys.stderr)
            drift += len(overweight)
            if held:
                print(f"{'HELD':8s} {world.name}/{name}/charactertemplate.yml")
        for rel, content in files.items():
            path = preset_dir / rel
            current = path.read_text("utf-8") if path.exists() else None
            if current == content:
                status = "ok"
            elif write:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, "utf-8")
                status = "wrote" if current is None else "updated"
            else:
                status = "DRIFT" if current is not None else "MISSING"
                drift += 1
            print(f"{status:8s} {world.name}/{name}/{rel}")
        if write:
            # Owned by BlueprintHunt. Created so the layout is complete; never
            # written into, never cleaned.
            (preset_dir / "blueprints").mkdir(parents=True, exist_ok=True)
    if drift:
        print(f"\n{drift} problem(s): files differ from what the inputs derive.", file=sys.stderr)
        return 1
    return 0


def run_spawn(
    world_name: str,
    preset_names: list[str] | None,
    vh_src: str | None,
    patch_path: Path,
    sandbox: str | None,
    reuse: bool,
    write: bool,
) -> int:
    """Probe terrain and (re)write spawn.yaml. The only mode that needs a server."""
    sf = _site_finder()
    world = load_world(world_name)
    seed = str(world.raw.get("seed") or "")
    if not seed:
        raise SystemExit(f"{world.root / 'world.yaml'}: no `seed`, so terrain cannot be probed")
    presets = [js.load_preset(n) for n in (preset_names or js.all_preset_names())]
    rows = patch_rows(world, presets)
    if not rows:
        print("no solved placements to derive a spawn from", file=sys.stderr)
        return 1

    patches: dict[str, dict] = {}
    if patch_path.exists():
        patches = sf.load_patches(patch_path)
    if not patch_covers(rows, patches):
        if reuse:
            raise SystemExit(
                f"{patch_path} does not cover the {len(rows)} window(s) this run needs; "
                "drop --reuse-patch to re-probe"
            )
        if not vh_src:
            raise SystemExit(
                "terrain probe needs a server install: pass --vh-src (or set VH_SRC) to "
                "<VALHEIM_ROOT>/<World>/data/bepinex. It runs in an rsync'd sandbox on its "
                "own port and savedir; nothing live is touched."
            )
        print(
            f"probing {len(rows)} window(s) at {SPAWN_PROBE_STEP_M:g} m for seed {seed}",
            file=sys.stderr,
        )
        run_patchscan(seed, rows, patch_path, vh_src, sandbox)
        patches = sf.load_patches(patch_path)
        if not patch_covers(rows, patches):  # pragma: no cover - defensive
            raise SystemExit(f"{patch_path}: probe did not return the requested windows")

    drift = 0
    for preset in presets:
        preset_dir = world.root / preset.name
        placements = load_placements(preset_dir)
        results = [
            probe_spawn(patches[f"{preset.name}#{pid}"], pl)
            for pid, pl in sorted(solved_placements(placements).items())
        ]
        for r in results:
            if "point" in r:
                p = r["point"]
                print(
                    f"  OK  {preset.name:18} {p['base']:26} -> ({p['x']}, {p['y']}, {p['z']}) "
                    f"ground={p['terrain_y']} (+{p['spawn_freeboard_m']} m) "
                    f"edge={p['dist_to_footprint_edge_m']}m base={p['dist_to_base_m']}m "
                    f"disc=+{p['disc_min_freeboard_m']}m score={p['score']}"
                )
            else:
                print(f"  !!  {preset.name:18} {r['base']:26} -> NO SPAWN: {r['refused']}")
        content = render_spawn(world, preset, results)
        path = preset_dir / SPAWN_FILE
        current = path.read_text("utf-8") if path.exists() else None
        if current == content:
            status = "ok"
        elif write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, "utf-8")
            status = "wrote" if current is None else "updated"
        else:
            status = "DRIFT" if current is not None else "MISSING"
            drift += 1
        print(f"{status:8s} {world.name}/{preset.name}/{SPAWN_FILE}")
    if drift:
        print(
            f"\n{drift} {SPAWN_FILE} file(s) disagree with a fresh terrain probe.",
            file=sys.stderr,
        )
        return 1
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list", help="list worlds and presets")
    for cmd, help_text in (("build", "write the tree"), ("check", "re-derive and diff, never write")):
        p = sub.add_parser(cmd, help=help_text)
        p.add_argument("world")
        p.add_argument("--preset", action="append", dest="presets")
    sp = sub.add_parser(
        "spawn",
        help=f"probe terrain and rewrite {SPAWN_FILE} (boots a sandboxed server)",
    )
    sp.add_argument("world")
    sp.add_argument("--preset", action="append", dest="presets")
    sp.add_argument(
        "--vh-src",
        default=os.environ.get("VH_SRC"),
        help="server install dir (<VALHEIM_ROOT>/<World>/data/bepinex); the probe runs in an "
        "rsync'd sandbox copy on its own port and savedir",
    )
    sp.add_argument("--patch", help="patch dump path (written by run_patchscan.sh)")
    sp.add_argument("--patch-sandbox", help="sandbox dir for run_patchscan.sh")
    sp.add_argument(
        "--reuse-patch", action="store_true", help="reuse an existing --patch instead of re-probing"
    )
    sp.add_argument(
        "--check",
        action="store_true",
        help=f"re-probe and diff, never write: exits 1 when {SPAWN_FILE} disagrees with terrain",
    )

    args = parser.parse_args(argv)
    if args.cmd == "list":
        worlds = sorted(p.parent.name for p in HERE.glob("*/world.yaml"))
        print("worlds:  " + (", ".join(worlds) or "(none)"))
        print("presets: " + ", ".join(js.all_preset_names()))
        print(f"owned:   {', '.join(OWNED)}")
        print(f"         {SPAWN_FILE}  (written by `spawn`, read by build/check)")
        print("other:   blueprints/, placements.yaml  (BlueprintHunt)")
        return 0
    if args.cmd == "spawn":
        default_patch = Path("/tmp/jumpstart-spawn") / f"patch-{args.world}.bin"
        return run_spawn(
            args.world,
            args.presets,
            args.vh_src,
            Path(args.patch) if args.patch else default_patch,
            args.patch_sandbox,
            reuse=args.reuse_patch,
            write=not args.check,
        )
    return run(args.world, args.presets, write=(args.cmd == "build"))


if __name__ == "__main__":
    raise SystemExit(main())
