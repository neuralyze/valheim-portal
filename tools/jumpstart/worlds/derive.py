# Sea level in WorldGenerator.GetHeight units. MEASURED three independent ways
# on the Pirate68 artefacts, because getting this number wrong is exactly how a
# jumpstart character ends up swimming:
#   1. Biome bands, 6.9 M cells of the 8 m grid. Swamp spans 27.46..33.84 with a
#      29.84 median -- a narrow band straddling 30, which is what a swamp is.
#      Ocean cells are clamped at <= 4.00, and 4.00 = 0.02 * 200: GetBiome's
#      oceanLevel is baseHeight 0.02 and GetHeight returns baseHeight * 200, so
#      that clamp is the ocean FLOOR some 26 m down, not the surface.
#   2. The 12,301-instance ZoneSystem location dump. Every land location type
#      floors at 30.50..31.11 (Grave1 30.50, Ruin1 31.02, StoneHouse4 31.04,
#      Crypt2 31.11) -- Valheim places land locations with m_minAltitude 1 above
#      the water. The ocean ones (ShipWreck01..04) sit at 29.0..30.9.
#   3. 30 / 200 = 0.15, the baseHeight the generator treats as the shoreline.
# tools/jumpstart/blueprints/site_finder.py uses WATER_LEVEL = 0.0, i.e. the
# ocean-floor clamp read as the surface, so its `water_dist_m` measures the
# distance to 30-m-deep water and its sites can sit below the waterline while
# passing. Reported to that file's owner; nothing here depends on those numbers.
SEA_LEVEL_M = 30.0

# Freeboard the written coordinate must clear the water plane by. Valheim's own
# rule for putting a land location down is m_minAltitude = 1 m (MEASURED above:
# the land-location floor is 30.50..31.11), so 1 m is the game's own definition
# of "on land" and 2 m is that with a metre of slack for the 1 m lattice, for the
# terrain the blueprint's flatten pass will move, and for shoreline waves. It is
# deliberately not higher: Swamp land tops out at +3.84 m world-wide on this
# seed, and a floor no swamp can meet is a floor that deletes Swamp spawns.
SPAWN_FREEBOARD_M = 2.0
# A spawn is a point; a player is not. Every 1 m sample within this radius must
# clear the water by SPAWN_DISC_FREEBOARD_M, so a candidate cannot be a one-cell
# pinnacle in a bog with water on all sides.
SPAWN_DISC_R_M = 4.0
SPAWN_DISC_FREEBOARD_M = 0.5
# Stand-off from the blueprint's own footprint, so nobody wakes up inside a wall
# once the base is materialised. Measured against footprint_xzy_m rotated by the
# placement's yaw -- the real rectangle, not the square the solver searched with.
SPAWN_FOOTPRINT_CLEAR_M = 6.0
# How far outside that rectangle a spawn may sit and still count as "at the
# base". 120 m is 20-25 s of walking and well inside view distance; past that the
# honest answer is that this site has no dry ground next to it and the placement
# needs re-solving, which is what the recorded refusal says.
SPAWN_SEARCH_MAX_M = 120.0
# The approach, sampled every metre from the spawn to the nearest point on the
# footprint rectangle. The ground must stay above water -- a spawn separated
# from its base by a channel is a spawn on the wrong side of a swim -- and must
# not step more than this per metre, which is what rules out a ravine.
SPAWN_PATH_FREEBOARD_M = 0.5
SPAWN_PATH_STEP_M = 1.5
# y is written as ceil(terrain + this). Up, never down: rounding a spawn down
# puts the player inside the ground, and ServerCharacters hands the triple
# straight to the client.
SPAWN_Y_CLEAR_M = 1.0
# Taste, stated so it can be argued with. Nearness first (the operator's
# complaint was distance and water, in that order), then the side the building
# faces (the placement's own declared intent), then dryness beyond the floor.
SPAWN_WEIGHTS = {"near": 0.45, "facade": 0.30, "dry": 0.25}
# 1 m is the resolution Valheim builds its terrain mesh at, so it is the only
# honest resolution for a point verdict. The 8 m seedscan grid is NOT usable
# here at any margin: run_scan.sh leaves pregeneration off, so its heights are
# river-free, and MEASURED at the operator's own spawn it reports 30.17 where the
# true river-aware height is 26.74 -- a 3.4 m error that flips the verdict from
# "land" to "three metres under water".
SPAWN_PROBE_STEP_M = 1.0
# Slack beyond the search radius so the disc and the approach of the outermost
# candidate are still inside the probed window.
SPAWN_PROBE_PAD_M = 12.0
# Candidates whose approach is actually walked, best score first. The score is a
# proxy for the approach verdict, and a truncated ranking is a bad proxy: the
# best-scoring 1000 points of a 40,000-point ring are all within a few metres of
# each other, so a cap alone would test one spot 1000 times and then refuse. The
# tries are therefore THINNED -- at most one per SPAWN_TRY_SEPARATION_M cell --
# which spends the same bounded work spread across the whole ring. MEASURED: a
# 120 m walk is ~150 samples, so 1024 tries is ~150 k samples, tenths of a
# second, and the refusal message reports how many were walked.
SPAWN_APPROACH_TRIES = 1024
SPAWN_TRY_SEPARATION_M = 8.0

