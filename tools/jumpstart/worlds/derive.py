def solved_placements(placements: dict | None) -> dict[str, dict]:
    """Placements that currently carry a solved site, by id."""
    out: dict[str, dict] = {}
    for pl in (placements or {}).get("placements") or []:
        sol = (pl or {}).get("solved") or {}
        if "x" in sol and "z" in sol:
            out[str(pl.get("id"))] = pl
    return out


def load_container_capacity(placements: dict | None) -> int | None:
    """Chest slot capacity of the placed base, if placements.yaml reports it."""
    if not placements:
        return None
    # BlueprintHunt's schema, counted out of the blueprint object list:
    #   containers: {by_prefab: {<piece>: n}, containers: n, slots_floor: n}
    # `slots_floor` is the conservative slot total, which is the number worth
    # comparing an overflow manifest against.
    total = 0
    seen = False
    for placement in placements.get("placements") or []:
        containers = (placement or {}).get("containers") or {}
        if "slots_floor" in containers:
            seen = True
            total += int(containers["slots_floor"])
    return total if seen else None


